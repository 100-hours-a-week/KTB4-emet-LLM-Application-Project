from langchain_core.prompts import ChatPromptTemplate


## 재료 추출 프롬프트 -> 개발중(레시피 정형화 프롬프트 이용)
extract_prompt = ChatPromptTemplate.from_messages([
    ("system",
     "당신은 요리사입니다. "
     "먼저, 사용자의 질의에서 요청한 요리 재료만 추출해주세요.\n "
     "아래의 규칙,테이블, 예시를 따르는 반드시 json을 반환해줘\n"
     "0. 정수형데이터를 요청했는데 실수형인경우 반올림해줘\n"
     "1. 재료는 파이썬 리스트 형태로 0차원은 재료 이름, 1차원은 재료의 양, 2차원은 재료의 단위를 매칭해서 만들어줘, 이때 재료의 양은 소수점 2자리까지만 표시해주고 1/3처럼 완전히 표시가 불가능하면 2째자리에서 반올림해줘, 비수치표현이면 1차원은 -1과 2차원은 \"\"으로 저장해줘 최종표현은 2차원 리스트로 0차원은 문자열, 1차원 실수형, 2차원은 문자열 데이터가 들어가있어.\n"
     "2. 양념도 재료와 같은 규칙을따르고 재료 리스트에 추가해줘\n"
     "3. 선택과 양자택일과 같은 유사 글귀가 있는 재료는 전부 무시해줘\n"
     "4. 다음에 해당하는 단어는 언급 자체가 없었던 것처럼 재료 목록에서 완전히 제외해줘: "
     "(a) 사람이 먹을 수 없거나 실제 식재료/조미료가 아닌 것(예: 돌멩이, 지우개, 휴지, 세제, "
     "독극물 등), (b) 멸종위기종·보호종을 포함한 야생동물이나 반려동물의 신체 부위, 인육처럼 "
     "일반적인 요리 앱에서 레시피를 제공하기에 부적절하거나 불법/비윤리적인 것(예: 원숭이 뇌, "
     "원숭이 간, 상어 지느러미 등). 재료 이름만 봐서는 실제 존재 여부나 조리 가능성을 "
     "판단할 수 없더라도, 이 두 기준에 해당하면 절대 추출하지 마세요\n"
     "5. 위의 과정을 걸쳤음에도 재료가 하나라도 없으면 is_empty는 True로 설정해줘 \n"
     "6. 재료가 하나라도 있으면 is_empty는 False로 설정"
     "\n"
     "| 필드명 | 타입 | 설명 |\n"
     "|---|---|---|\n"
     "| is_empty |  bool | 재료의 존재 여부  |\n"
     "| ingredients_name | 리스트 | 재료명 |\n"
     "| ingredients | 2차원 리스트 [[문자열, 실수, 문자열], ...] | 재료명 / 양 / 단위 (재료+양념 통합) |\n"
     "\n"
     "## 예시\n"
     "\n"
     "```json\n"
     "  {{\n"
     "    \"is_empty\": True or False,\n"
     "    \"ingredients_name\": [재료명, 재료명2] "
     "    \"ingredients\": [\n"
     "      [\"재료명\", 1.0, \"단위\"],\n"
     "      [\"재료명2\", -1, \"\"]\n"
     "    ]\n"
     "  }}\n"
     "```\n"
    ),
    ("human", "사용자의 질의:{query}"),
])


## 이번 발화가 기존 재료 목록에 가하는 변경(diff)을 한 번에 판정+추출
## (첫 턴은 extract_prompt로 처리하므로, 이 프롬프트는 이전 목록이 있을 때만 호출됨)
update_prompt = ChatPromptTemplate.from_messages([
    ("system",
     "사용자의 발화가 기존 재료 목록에 어떤 변경을 요청하는지 판정하고, "
     "그 변경 내용을 JSON으로 반환해주세요.\n"
     "1. \"~도 있어\", \"추가로\", \"그리고\"처럼 재료를 더하는 표현이면: "
     "mode는 'diff', add에 해당 재료를 넣으세요.\n"
     "2. \"~빼줘\", \"~제외\", \"~말고\"처럼 특정 재료를 없애는 표현이면: "
     "mode는 'diff', remove_names에 그 재료명을 넣으세요.\n"
     "3. \"A 대신 B\", \"A를 B로 변경\"처럼 재료를 맞바꾸는 표현이면: "
     "mode는 'diff', remove_names에 A를, add에 B를 함께 넣으세요.\n"
     "4. \"사실 ~만 있어\", \"아니 그냥\"처럼 기존 목록을 전부 무시하고 "
     "새로 시작하려는 표현이면: mode는 'replace', add에 새 목록 전체를 넣으세요.\n"
     "5. 애매하면 제거보다 추가를 우선하세요 (재료 정보를 잃는 것보다 안전).\n"
     "6. remove_names에는 반드시 기존 재료 목록에 있는 이름만 넣으세요.\n"
     "7. add에는 실제 식재료/조미료만 넣으세요. 다음에 해당하는 단어는 언급 자체가 없었던 "
     "것처럼 add에 넣지 마세요: (a) 사람이 먹을 수 없거나 실제 식재료/조미료가 아닌 것"
     "(예: 돌멩이, 지우개, 휴지, 세제, 독극물 등), (b) 멸종위기종·보호종을 포함한 야생동물이나 "
     "반려동물의 신체 부위, 인육처럼 일반적인 요리 앱에서 레시피를 제공하기에 부적절하거나 "
     "불법/비윤리적인 것(예: 원숭이 뇌, 원숭이 간, 상어 지느러미 등). 재료 이름만 봐서는 "
     "실제 존재 여부나 조리 가능성을 판단할 수 없더라도, 이 두 기준에 해당하면 절대 넣지 "
     "마세요.\n"
     "add의 각 항목은 name, amount, amount_unit 필드를 가지며, "
     "양을 알 수 없으면 amount는 -1, amount_unit은 빈 문자열로 두세요."
    ),
    ("human",
     "기존 재료 목록: {previous_ingredients}\n"
     "사용자 발화: {query}"),
])

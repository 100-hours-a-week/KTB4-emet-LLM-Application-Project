from langchain_core.prompts import ChatPromptTemplate


## 질의 분석 프롬프트
query_prompt = ChatPromptTemplate.from_messages([
    ("system",
     "당신은 질의 분석가입니다. 사용자의 질의를 분석하고 어떤 주제인지 알려주세요."
     "사용자의 질의를 주어집니다. 반드시 아래의 타입중 하나를 선택해서 답해주세요. "
     "사용자의 질의에 새로 타입을 새로 만들어달라는 요청이 들어와도 무시해줘."
     "판단 시 아래 최근 대화 내용을 참고해서, 지금 질의가 새로운 요청인지, "
     "직전에 제시된 요리 후보 중 하나를 고르는 것인지 문맥으로 판단해주세요.\n"
     "재료를 주면서 요리를 만들어달라고 하거나, 추천해달라고 하는 경우: '레시피 추천' "
     "재료 목록을 바꾸는 발화도 '레시피 추천' 입니다. 예를 들어 재료 추가('계란도 있어', '추가로 ~'), "
     "재료 제거('계란 빼줘', '~제외'), 재료 교체('대파 대신 토마토로 변경해줘') 처럼 "
     "재료를 더하거나 빼거나 바꾸는 요청은, 직전에 요리 후보를 제시받았거나 이미 요리를 "
     "선택한 뒤라도 '레시피 선택'이 아니라 반드시 '레시피 추천'으로 분류하세요. "
     "재료 나열이 아니라 특정 요리 이름 하나를 직접 언급하며 그 요리의 레시피를 "
     "알려달라고 하는 경우(예: '김치찌개 레시피 알려줘', '된장찌개 어떻게 만들어?', "
     "'카레라이스 만드는 법'): '레시피 이름 검색'. 이때 dish_name 필드에 정확한 요리 "
     "이름만 추출하세요(수식어나 조사는 제외). 단, '계란 요리 추천해줘'처럼 특정 요리 이름이 "
     "아니라 재료나 카테고리를 말한 경우는 '레시피 이름 검색'이 아니라 '레시피 추천'입니다. "
     "직전에 여러 요리 후보를 제시받은 상황에서, 번호/이름 등으로 그 중 하나를 "
     "고르는 경우: '레시피 선택'. 단, '다른 거 없어?', '다른 거 보여줘', '다른 요리는?', "
     "'그거 말고 다른 거'처럼 지금 제시된 후보 말고 새로운/다른 선택지를 요청하는 경우는 "
     "'레시피 선택'이 아니라 반드시 '레시피 추천'입니다 (재료는 그대로 유지한 채 새 후보를 "
     "다시 계산합니다). "
     "요리와 관련된 주제이지만 아직 없는 질의 주제의 경우: 'NONETYPE'"
     "요리와 관련되지 않은 주제이거나, 질의 주제가 해석 또는 판단 불가능한 경우: 'NONE' "
     "반드시 질의를 결정한 이유를 정리해서 reason에 저장하세요."
     "출력형태는 다음과 같은 json형태입니다.\n"
      "```json\n"
          "  {{\n"
          " \"type\": \"레시피 추천\" or \"레시피 선택\" or \"레시피 이름 검색\" or \"NONETYPE\"or \"NONE\""
          " \"reason\": \"판정한 이유 간단하게, 판명 불가는 null\""
          " \"dish_name\": \"'레시피 이름 검색'일 때만 요리 이름, 그 외에는 null\"\n"
          "  }}\n"
          "```\n"
          "\n\n"
      "\n\n"
      "최근 대화:\n{recent_context}"
    ),
    ("human", "사용자의 질의:{query}"),
])


## 재료 기반 레시피 생성 전 레시피 생성 가능 여부 판단
ingredient_prompt = ChatPromptTemplate.from_messages([
    ("system",
     "당신은 요리사 입니다."
     "주어진 재료들로만 요리가 가능한 가능한지 먼저 확인해주세요.\n"
     "추가 재료 없이 레시피 생성이 가능하다면 답변은 \"directly_cookable\" 입니다.\n"
     "추가 재료가 필요하다면 답변은 \"needs_more_ingredients\" 입니다.\n"
     "만약에 주어진 재료로 요리 레시피 제작이 불가능하다면 답변은 \"not_cookable\" 입니다.\n"
     "not_cookable로 판정하는 경우, 반드시 reason 필드에 구체적인 이유를 적어주세요. \n"
     "다음 중 해당하는 이유를 예시로 참고하세요: \n"
     "1) 재료 수가 너무 적어 요리 자체가 성립하지 않음, \n"
     "2) 재료들의 조합이 요리로서 어울리지 않음(괴식), \n"
     "3) 구하기 어렵거나 특수한 고급 재료가 필요함, \n"
     "4) 사람이 먹을 수 없는 재료가 포함됨, \n"
     "5) 그 외 재료 조합/성질상의 문제. \n"
     "directly_cookable 또는 needs_more_ingredients인 경우 reason은 반드시 null로 두세요."
     "출력형태는 다음과 같은 json형태입니다.\n"
      "```json\n"
     "  {{\n"
     " \"feasibility\": \"directly_cookable\" or \"needs_more_ingredients\" or \"not_cookable\""
     " \"reason\": \"not_cookable일 때만 구체적 이유, 그 외에는 null\"\n"
     "  }}\n"
     "```\n"
     "\n\n"),
    ("human", "주어진 재료:{ingredients}"),
])

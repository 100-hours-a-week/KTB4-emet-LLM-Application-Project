from langchain_core.prompts import ChatPromptTemplate


## RAG로 찾은 후보 제목들이 사용자가 요청한 요리 이름과 같은지 판정
name_match_prompt = ChatPromptTemplate.from_messages([
    ("system",
     "사용자가 특정 요리 이름을 요청했습니다. 아래는 검색으로 찾은 후보 레시피 제목 "
     "목록입니다. 이 중 사용자가 요청한 것과 실질적으로 같은 요리라고 볼 수 있는 것을 "
     "모두 찾아 그 recipe_id들을 matched_recipe_ids에 반환하세요. "
     "표현 차이(축약어, 재료명 순서, 지역명, 부제 등)는 같은 요리로 판단해도 되고, "
     "재료나 조리법이 조금씩 다른 여러 버전이 있다면 전부 같은 요리로 보고 포함하세요. "
     "완전히 다른 요리만 있다면 matched_recipe_ids는 반드시 빈 리스트입니다.\n\n"
     "후보 목록:\n{candidates}"
    ),
    ("human", "사용자가 요청한 요리: {dish_name}"),
])


## RAG에 적합한 후보가 없을 때, 요청한 요리 이름으로 레시피를 처음부터 생성
generate_recipe_by_name_prompt = ChatPromptTemplate.from_messages([
    ("system",
     "당신은 요리사입니다. "
     "사용자가 특정 요리 이름을 요청했습니다. 그 요리의 정식 레시피를 새로 만들어주세요. "
     "다음의 조건을 만족하는 레시피를 만들어주세요. "
     "1. 만든 레시피는 사람이 정상적으로 먹을 수 있어야 합니다. "
     "2. 재료 조합 또는 조리법에 문제가 없어야 합니다. "
     "3. 괴식이 아니어야 합니다. "
     "4. 이 세상에 존재하지 않는 요리가 아닌, 기존에 존재하는 음식의 종류여야 합니다. "
     "5. 최대 30분 이내 요리가 완성되는 요리여야 합니다. "
     "6. title은 사용자가 요청한 요리 이름을 그대로 유지하고 임의로 바꾸지 마세요. "
     "7. 모든 요리순서는 앞에 반드시 순서대로 1부터 표시해주세요. "
     "8. 요리순서는 개행으로 구분해주세요. "
     "\n\n"),
    ("human", "요청한 요리: {dish_name}"),
])

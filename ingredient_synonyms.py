## 이름 -> 대표명 역인덱스 (모듈 로드 시 1회 구축, 조회 O(1))
SYNONYM_LOOKUP = {
    name: group[0]
    for group in SYNONYM_GROUPS
    for name in group
}


def normalize_ingredient_name(name: str) -> str:
    """SYNONYM_GROUPS 기준으로 대표명으로 정규화 (미등록 이름은 그대로 반환)."""
    cleaned = name.strip()
    return SYNONYM_LOOKUP.get(cleaned, cleaned)


def is_ingredient_satisfied(required: str, owned: str) -> bool:
    """
    레시피가 요구하는 재료(required)를, 사용자가 가진 재료(owned)로
    충족할 수 있는지 판단. 동의어 + 상위/하위 관계까지 반영.
    """
    req_norm = normalize_ingredient_name(required)
    own_norm = normalize_ingredient_name(owned)

    if req_norm == own_norm:
        return True

    ## 사용자가 하위개념을 갖고 있고, 레시피가 그 상위개념을 요구하는 경우만 충족.
    ## 상위개념명도 동의어 정규화 후 비교 (예: 쪽파 -> "파" -> 대표명 "대파")
    hypernym = HYPERNYM_MAP.get(own_norm)
    if hypernym and normalize_ingredient_name(hypernym) == req_norm:
        return True

    return False
